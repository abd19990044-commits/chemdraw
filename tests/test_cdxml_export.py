from xml.etree import ElementTree as ET

from cdxml_export import generate_reaction_cdxml, generate_single_compound_cdxml


def _arrow(root):
    return next(g for g in root.findall("page/graphic") if g.get("ArrowType"))


def test_single_compound_cdxml_is_editable_fragment():
    data = generate_single_compound_cdxml("CC(=O)OC1=CC=CC=C1C(=O)O", "Aspirin")
    assert data is not None
    root = ET.fromstring(data)
    page = root.find("page")
    assert page is not None
    fragments = page.findall("fragment")
    assert len(fragments) == 1
    assert len(fragments[0].findall("n")) > 0
    assert len(fragments[0].findall("b")) > 0
    assert not page.findall("graphic")


def test_cdxml_contains_editable_fragments_arrow_and_conditions():
    data = generate_reaction_cdxml(
        [(2, "[H][H]"), (1, "O=O")],
        [(2, "O")],
        arrow_top="catalyst",
        arrow_bottom="25 °C",
        arrow_style="forward",
        title="2 H2 + O2 -> 2 H2O",
        small_as_formula=False,
    )
    assert data is not None
    root = ET.fromstring(data)
    assert root.tag == "CDXML"
    page = root.find("page")
    assert page is not None
    fragments = page.findall("fragment")
    assert len(fragments) == 3
    assert sum(len(f.findall("n")) for f in fragments) > 0
    assert sum(len(f.findall("b")) for f in fragments) > 0
    assert _arrow(root).get("ArrowType") == "FullHead"
    texts = ["".join(t.itertext()) for t in page.findall("t")]
    assert "2" in texts
    assert "catalyst" in texts
    assert "25 °C" in texts


def test_cdxml_forward_arrow_points_right_in_chemdraw_coordinate_order():
    data = generate_reaction_cdxml([(1, "C=C")], [(1, "CC")])
    root = ET.fromstring(data)
    box = [float(v) for v in _arrow(root).get("BoundingBox").split()]
    assert box[0] > box[2]


def test_cdxml_smart_mode_matches_condensed_small_species():
    data = generate_reaction_cdxml(
        [(1, "C=C"), (1, "[H][H]")],
        [(1, "CC")],
        arrow_top="Ni",
        arrow_bottom="150 °C",
        small_as_formula=True,
    )
    assert data is not None
    root = ET.fromstring(data)
    text = " ".join("".join(t.itertext()) for t in root.findall("page/t"))
    # Smart image previews may be condensed; downloadable CDXML must remain
    # a true editable molecule graph (not just text plus graphic lines).
    fragments = root.findall("page/fragment")
    assert len(fragments) == 3
    assert sum(len(f.findall("n")) for f in fragments) >= 6
    assert all(not any(g.get("GraphicType") == "Line" and not g.get("ArrowType") for g in root.findall("page/graphic")) for _ in [0])


def test_cdxml_equilibrium_arrow():
    data = generate_reaction_cdxml(
        [(1, "CC=O")],
        [(1, "CC=O")],
        arrow_style="equilibrium",
    )
    assert data is not None
    root = ET.fromstring(data)
    assert _arrow(root).get("ArrowType") == "Equilibrium"


def test_cdxml_is_source_neutral():
    data = generate_reaction_cdxml(
        [(1, "C=C"), (1, "[H][H]")],
        [(1, "CC")],
        arrow_top="Ni",
        arrow_bottom="150 °C",
    )
    assert data is not None
    text = data.decode("utf-8")
    root = ET.fromstring(data)
    assert "CreationProgram" not in root.attrib
    assert "Creator" not in root.attrib
    assert "Producer" not in root.attrib
    assert "Chemistry Drawing Bot" not in text
    assert "generated by" not in text.lower()
    assert "<!--" not in text


def test_cdxml_preserves_chiral_wedge_or_dash_depiction():
    data = generate_reaction_cdxml(
        [(1, "C[C@H](O)C(=O)O")],
        [(1, "C[C@H](O)C(=O)O")],
        small_as_formula=False,
    )
    assert data is not None
    root = ET.fromstring(data)
    displays = [bond.get("Display") for bond in root.findall("page/fragment/b") if bond.get("Display")]
    assert any(display in {"WedgeBegin", "WedgedHashBegin", "WedgeEnd", "WedgedHashEnd"} for display in displays)


def test_cdxml_uses_normal_chemdraw_font_scale():
    data = generate_reaction_cdxml(
        [(1, "C=C"), (1, "[H][H]")],
        [(1, "CC")],
        arrow_top="Ni",
        arrow_bottom="150 °C",
    )
    assert data is not None
    root = ET.fromstring(data)
    assert 8 <= float(root.get("LabelSize", "0")) <= 14
    assert 8 <= float(root.get("CaptionSize", "0")) <= 14
    sizes = [float(s.get("size", "0")) for s in root.findall("page/t/s")]
    assert sizes
    assert max(sizes) <= 14
    assert min(sizes) >= 8
